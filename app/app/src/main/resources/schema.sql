-- ============================================================
--  Bot de trading spot BTCUSDT - esquema de base de datos
--  Motor: R2DBC + H2 (en memoria)
-- ============================================================

-- Conjunto de niveles ("grillas") definido por el usuario.
CREATE TABLE IF NOT EXISTS grid_set (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol          VARCHAR(32)      NOT NULL,
    floor_price     DECIMAL(24, 8)   NOT NULL,
    ceil_price      DECIMAL(24, 8)   NOT NULL,
    level_count     INT              NOT NULL,
    btc_inventory   DECIMAL(24, 8)   NOT NULL,
    usdt_reserve    DECIMAL(24, 8)   NOT NULL,
    fee_rate        DECIMAL(12, 8)   NOT NULL,
    status          VARCHAR(16)      NOT NULL,
    cycle_sells     INT              NOT NULL DEFAULT 0,
    created_at      TIMESTAMP        NOT NULL,
    exhausted_at    TIMESTAMP,
    origin_set_id   BIGINT
);

-- Cada nivel (banda) del conjunto. weight_percent reparte el inventario de BTC.
CREATE TABLE IF NOT EXISTS grid_level (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grid_set_id     BIGINT           NOT NULL,
    level_index     INT              NOT NULL,
    lower_price     DECIMAL(24, 8)   NOT NULL,
    upper_price     DECIMAL(24, 8)   NOT NULL,
    weight_percent  DECIMAL(12, 8)   NOT NULL,
    btc_allocated   DECIMAL(24, 8)   NOT NULL,
    holding         BOOLEAN          NOT NULL,
    entry_price     DECIMAL(24, 8),
    btc_bought      DECIMAL(24, 8)   NOT NULL DEFAULT 0,
    usdt_spent      DECIMAL(24, 8)   NOT NULL DEFAULT 0,
    btc_sold        DECIMAL(24, 8)   NOT NULL DEFAULT 0,
    usdt_received   DECIMAL(24, 8)   NOT NULL DEFAULT 0,
    pnl_usdt        DECIMAL(24, 8)   NOT NULL DEFAULT 0,
    pnl_btc         DECIMAL(24, 8)   NOT NULL DEFAULT 0,
    trade_count     INT              NOT NULL DEFAULT 0,
    cycle_sells     INT              NOT NULL DEFAULT 0
);

-- Migración suave para bases ya creadas (Neon): añade las columnas nuevas si faltan.
ALTER TABLE grid_level ADD COLUMN IF NOT EXISTS cycle_sells INT NOT NULL DEFAULT 0;

CREATE INDEX IF NOT EXISTS idx_grid_level_set ON grid_level (grid_set_id);

-- Historial de operaciones (compras y ventas) de cada nivel.
CREATE TABLE IF NOT EXISTS trade_history (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grid_set_id     BIGINT           NOT NULL,
    grid_level_id   BIGINT           NOT NULL,
    level_index     INT              NOT NULL,
    side            VARCHAR(8)       NOT NULL,
    price           DECIMAL(24, 8)   NOT NULL,
    quantity        DECIMAL(24, 8)   NOT NULL,
    amount          DECIMAL(24, 8)   NOT NULL,
    fee             DECIMAL(24, 8)   NOT NULL,
    pnl_usdt        DECIMAL(24, 8)   NOT NULL DEFAULT 0,
    pnl_btc         DECIMAL(24, 8)   NOT NULL DEFAULT 0,
    created_at      TIMESTAMP        NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_trade_set ON trade_history (grid_set_id);
CREATE INDEX IF NOT EXISTS idx_trade_level ON trade_history (grid_level_id);

-- Alertas pendientes para operar manualmente por zona de compra/venta
CREATE TABLE IF NOT EXISTS grid_alert (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grid_set_id       BIGINT           NOT NULL,
    grid_level_id     BIGINT           NOT NULL,
    level_index       INT              NOT NULL,
    type              VARCHAR(8)       NOT NULL,
    status            VARCHAR(12)      NOT NULL,
    trigger_price     DECIMAL(24, 8)   NOT NULL,
    suggested_quantity DECIMAL(24, 8)  NOT NULL,
    suggested_price   DECIMAL(24, 8)   NOT NULL,
    resolved_at       TIMESTAMP,
    trade_id          BIGINT,
    note              VARCHAR(255),
    created_at        TIMESTAMP        NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_grid_alert_set ON grid_alert (grid_set_id);
CREATE INDEX IF NOT EXISTS idx_grid_alert_level ON grid_alert (grid_level_id);
CREATE INDEX IF NOT EXISTS idx_grid_alert_status ON grid_alert (status);
